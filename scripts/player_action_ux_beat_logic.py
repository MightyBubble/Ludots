def apply_beat_logic(cases: list[dict]) -> None:
    missing = []
    for c in cases:
        cid = c["id"]
        for i, b in enumerate(c.get("beats") or []):
            key = f"{cid}#{i}"
            logic = (BEAT_LOGIC.get(key) or "").strip()
            if not logic:
                missing.append(key)
                continue
            b["logic"] = logic
            b.pop("feel", None)
    if missing:
        raise SystemExit(f"BEAT_LOGIC missing {len(missing)} keys, e.g. {missing[:10]}")
